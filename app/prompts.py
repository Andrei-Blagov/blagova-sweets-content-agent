def build_user_prompt(
    *,
    content: str,
    platform: str,
    style: str,
    goal: str,
    max_length: int,
    cta: bool,
    hashtags: bool,
) -> str:
    style_key = style.strip().lower()
    style_hint = STYLE_HINTS.get(style_key, f"пользовательский стиль: {style.strip()}")
    platform_hint = PLATFORM_HINTS.get(platform, PLATFORM_HINTS[Platform.UNIVERSAL.value])
    goal_hint = GOAL_HINTS.get(goal, GOAL_HINTS[Goal.PRODUCT.value])

    cta_line = (
        "Добавь естественный CTA.\n"
        "CTA НЕ должен создавать вымышленные факты.\n"
        "Без подтверждения посещения нельзя: «Приходите», «Заходите», «Ждём вас», «Загляните к нам», «Попробуйте у нас».\n"
        "Без подтверждения заказа нельзя: «Закажите», «Оформите заказ», «Напишите нам для заказа».\n"
        "Без подтверждения наличия нельзя: «Уточните наличие», «Успейте купить», «Пока есть в наличии».\n"
        "Если коммерческое действие не подтверждено FACTS_FROM_SOURCE — используй нейтральный engagement CTA "
        "(короткий вопрос или мягкое вовлечение по теме поста). Не копируй одну и ту же фразу механически."
        if cta
        else (
            "CTA не добавляй.\n"
            "Без подтверждения посещения в FACTS_FROM_SOURCE также нельзя писать приглашения "
            "«приходите», «заходите», «ждём вас», «загляните», «попробуйте у нас» и аналоги."
        )
    )
    hashtags_line = (
        "В конце добавь максимум 3–5 релевантных хэштегов."
        if hashtags
        else "Хэштеги не добавляй."
    )

    return f"""
Ты автор постов в соцсетях. Напиши короткий пост по этой теме в заданном стиле.

Площадка: {platform}
{platform_hint}

Стиль: {style}
Описание стиля: {style_hint}

Цель поста: {goal}
{goal_hint}

Лимит длины: {max_length} символов
{cta_line}
{hashtags_line}

FACTS_FROM_SOURCE (единственный источник текущих фактов):
\"\"\"
{content}
\"\"\"
""".strip()
