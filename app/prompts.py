def build_system_prompt(*, max_length: int) -> str:
    return f"""
Ты автор постов в соцсетях для пекарни BLAGOVA_SWEETS.

{BRAND_CONTEXT}

{ANTI_HALLUCINATION_RULES}

Ограничения ответа:
- верни ТОЛЬКО готовый текст поста;
- без предисловий вроде «Вот ваш пост», «Конечно»;
- без markdown-заголовков и пояснений процесса;
- длина поста строго не больше {max_length} символов.
""".strip()


def build_user_prompt(
    *,
    content: str,
    platform: str,
    style: str,
    goal: str,
    max_length: int,
    cta: bool,
    hashtags: bool,
) -> str:
    style_key = style.strip().lower()
    style_hint = STYLE_HINTS.get(style_key, f"пользовательский стиль: {style.strip()}")
    platform_hint = PLATFORM_HINTS.get(platform, PLATFORM_HINTS[Platform.UNIVERSAL.value])
    goal_hint = GOAL_HINTS.get(goal, GOAL_HINTS[Goal.PRODUCT.value])

    cta_line = (
        "Добавь естественный CTA без телефона, ссылок, адреса и условий доставки "
        "(например: «Напишите нам, чтобы уточнить наличие»)."
        if cta
        else "CTA не добавляй."
    )
    hashtags_line = (
        "В конце добавь максимум 3–5 релевантных хэштегов."
        if hashtags
        else "Хэштеги не добавляй."
    )

    return f"""
Ты автор постов в соцсетях. Напиши короткий пост по этой теме в заданном стиле.

Площадка: {platform}
{platform_hint}

Стиль: {style}
Описание стиля: {style_hint}

Цель поста: {goal}
{goal_hint}

Лимит длины: {max_length} символов
{cta_line}
{hashtags_line}

Исходный контент:
\"\"\"
{content}
\"\"\"
""".strip()
